operator = input("enter an operator(+,-,*,/): ")
num1 = float(input("enter no. one: "))
num2 = float(input("enter no. second: "))

if operator == "+":
   result = num1 + num2
   print(result)

elif operator == "-":
   result = num1 - num2
   print(result) 

elif operator == "*":
   result = num1 * num2
   print(result)

elif operator == "/":
   result = num1 / num2
   print (result)     